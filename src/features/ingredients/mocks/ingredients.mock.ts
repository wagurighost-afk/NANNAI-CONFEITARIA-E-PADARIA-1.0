import type { Ingredient } from '@/features/ingredients/types/ingredient.types'
import { resolveIngredientStatus } from '@/features/ingredients/utils/resolveIngredientStatus'

function buildIngredient(
  partial: Omit<Ingredient, 'status' | 'history' | 'relatedRecipes' | 'movements'> & {
    history?: Ingredient['history']
    relatedRecipes?: Ingredient['relatedRecipes']
    movements?: Ingredient['movements']
  },
): Ingredient {
  const status = resolveIngredientStatus({
    currentStock: partial.currentStock,
    minimumStock: partial.minimumStock,
    expirationDate: partial.expirationDate,
  })

  return {
    ...partial,
    status,
    history: partial.history ?? [],
    relatedRecipes: partial.relatedRecipes ?? [],
    movements: partial.movements ?? [],
  }
}

