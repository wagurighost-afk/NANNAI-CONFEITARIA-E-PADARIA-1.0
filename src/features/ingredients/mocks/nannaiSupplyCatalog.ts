function buildSupplyIngredient(row: SupplyRow): Ingredient {
  const [code, name, category, sourceUnit] = row
  const unit = UNIT_MAP[sourceUnit]

  return {
    id: `ing-nannai-${code}`,
    ingredientCode: code,
    sector: 'CONFEITARIA_PADARIA',
    name,
    description: `Item da lista oficial de Confeitaria/Padaria - ${category}.`,
    category,
    unit,
    supplier: '',
    averageCost: 0,
    currentStock: 0,
    minimumStock: 0,
    maximumStock: 0,
    expirationDate: '',
    lot: '',
    location: 'NANNAI SUPRI MURO ALTO',
    status: 'NAO_CONFIGURADO',
    notes:
      `Unidade original: ${sourceUnit}. ` +
      'Estoque, mínimo, máximo, custo e validade ainda não configurados.',
    createdAt: IMPORTED_AT,
    updatedAt: IMPORTED_AT,
    history: [],
    relatedRecipes: [],
    movements: [],
  }
}

const codes = SUPPLY_ROWS.map(([code]) => code)

if (new Set(codes).size !== SUPPLY_ROWS.length) {
  throw new Error('O catálogo NANNAI possui códigos duplicados.')
}

if (SUPPLY_ROWS.length !== 130) {
  throw new Error(
    `Quantidade inesperada no catálogo NANNAI: ${SUPPLY_ROWS.length}. Esperado: 130.`,
  )
}

export const NANNAI_SUPPLY_CATALOG: Ingredient[] =
  SUPPLY_ROWS.map(buildSupplyIngredient)
