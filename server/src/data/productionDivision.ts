export function getProductionDivisionByEmployeeId(employeeId: string): ProductionDivisionEntry | undefined {
  return PRODUCTION_DIVISION.find((entry) => entry.employeeId === employeeId)
}

export function toEmployeeProductionItems(products: readonly string[]) {
  return products.map((name, index) => ({
    id: `prod-${index + 1}`,
    name,
    target: 'Produção diária',
  }))
}
